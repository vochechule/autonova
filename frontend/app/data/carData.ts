export const getBrandsList = () => {
  return Object.entries(carBrands)
    .map(([key, brand]) => ({
      value: key,
      label: brand.name,
      logo: `/logos/${key}.png` // Cesta k logu značky
    }))
    .sort((a, b) => a.label.localeCompare(b.label, 'cs')); // Abecední řazení česky
};

export const getModelsList = (brandKey: string) => {
  if (!brandKey || !carBrands[brandKey as keyof typeof carBrands]) {
    return [];
  }
  
  return carBrands[brandKey as keyof typeof carBrands].models
    .map(model => ({
      value: model.toLowerCase().replace(/\s+/g, '_').replace(/[^a-z0-9_]/g, ''),
      label: model
    }))
    .sort((a, b) => a.label.localeCompare(b.label, 'cs')); // Abecední řazení česky
};

export const getBrandsGroupedByLetter = () => {
  const brands = getBrandsList();
  const grouped: { [key: string]: typeof brands } = {};
  
  brands.forEach(brand => {
    const firstLetter = brand.label.charAt(0).toUpperCase();
    if (!grouped[firstLetter]) {
      grouped[firstLetter] = [];
    }
    grouped[firstLetter].push(brand);
  });
  
  return grouped;
};
